/**
 * 쿼리별 캐시 유지 시간(staleTime)을 한곳에 모읍니다.
 *
 * <p>화면마다 {@code staleTime: 0}을 적어 두는 방식은 QueryProvider의 기본값(1분)을
 * 무력화하면서도, 왜 0이어야 하는지는 남기지 않습니다. 그 결과 탭을 옮길 때마다
 * 같은 목록을 다시 받아오고, 정작 실시간성이 필요한 곳과 구분되지 않습니다.</p>
 *
 * <p>대부분의 목록은 변경 시점을 이미 알고 있습니다 — 취소·넘기기 같은 mutation이
 * {@code invalidateQueries}로 갱신을 보장하므로, 그 사이에는 캐시를 믿어도 됩니다.</p>
 */

/**
 * 서버만 바꿀 수 있어 클라이언트가 변경 시점을 알 수 없는 데이터.
 *
 * 결제 승인 여부처럼 외부(PG·배치)에서 바뀌는 값이라 매번 확인해야 한다.
 */
export const REALTIME = 0;

/**
 * 사용자의 행동으로 바뀌지만, 그 행동이 mutation을 거치는 데이터.
 *
 * 예매 목록·대기 목록이 여기 해당한다. 취소하면 invalidateQueries가 즉시
 * 갱신하므로 그 사이 30초는 캐시를 써도 화면이 틀리지 않는다.
 */
export const SHORT = 30 * 1000;

/**
 * 자주 바뀌지 않는 데이터.
 *
 * 프로필·지난 예매처럼 한 세션 안에서 거의 변하지 않는 값이다.
 */
export const LONG = 5 * 60 * 1000;
